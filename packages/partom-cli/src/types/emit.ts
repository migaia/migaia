/** Text of the `.d.ts` that fills `IPartTypeRegistry`; pure and stable for the same input. */
import type { ITypesData } from './collect.ts'
import { schemaType } from './schema-type.ts'

/** Union of addresses: static ones as literals, template rows as template-literal types. */
function addressesType(data: ITypesData): string {
  /** Members in collection order. */
  const members = data.addresses.map((entry) =>
    entry.row
      ? `\`\${${JSON.stringify(entry.address)}}@row:\${string}\``
      : JSON.stringify(entry.address)
  )
  return members.length === 0 ? 'never' : members.join('\n      | ')
}

/** Object type of state paths. */
function statesType(data: ITypesData): string {
  return `{\n${data.states.map((entry) => `      ${JSON.stringify(entry.path)}: ${schemaType(entry.schema)}`).join('\n')}\n    }`
}

/** Object type of events by address, then by event name. */
function eventsType(data: ITypesData): string {
  /** Event members grouped by address in first-seen order. */
  const byAddress = new Map<string, string[]>()
  for (const entry of data.events) {
    /** Members of the address. */
    const members = byAddress.get(entry.address) ?? []
    members.push(`${JSON.stringify(entry.event)}: ${schemaType(entry.detail)}`)
    byAddress.set(entry.address, members)
  }
  /** Address lines. */
  const lines: string[] = []
  for (const [address, members] of byAddress)
    lines.push(`      ${JSON.stringify(address)}: { ${members.join('; ')} }`)
  return `{\n${lines.join('\n')}\n    }`
}

/** Object type of resources. */
function resourcesType(data: ITypesData): string {
  /** Resource lines. */
  const lines: string[] = []
  for (const resource of data.resources) {
    /** Command members. */
    const commands: string[] = []
    for (const [name, args] of Object.entries(resource.commands))
      commands.push(`${JSON.stringify(name)}: ${schemaType(args)}`)
    lines.push(
      `      ${JSON.stringify(resource.id)}: { params: ${schemaType(resource.params)}; result: ${schemaType(resource.result)}; commands: { ${commands.join('; ')} } }`
    )
  }
  return `{\n${lines.join('\n')}\n    }`
}

/** Body of the generated declaration file (without the ownership line). */
export function typesBody(data: ITypesData): string {
  return [
    `// Generated by partom types; regenerate after changing blueprints or definitions.`,
    `export {}`,
    ``,
    `declare module '@migaia/part-host' {`,
    `  interface IPartTypeRegistry {`,
    `    addresses: ${addressesType(data)}`,
    `    states: ${statesType(data)}`,
    `    events: ${eventsType(data)}`,
    `    resources: ${resourcesType(data)}`,
    `  }`,
    `}`,
    ``
  ].join('\n')
}
