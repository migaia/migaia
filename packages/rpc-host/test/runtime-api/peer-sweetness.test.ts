import { RUNTIME_API_CAPABILITIES } from '../../dist/remote/runtime-api/constants.js'
import { describe, expect, it, vi } from 'vitest'
import { createRuntimePeer } from '../../dist/remote/runtime-api/peer.js'
import { runtimeSources } from './fixture.js'

describe('Runtime Peer convenience', () => {
  it('defaults self and report before genuine source preparation', async () => {
    /** Independent source offers observe the actual Core-generated addresses. */
    const channel = runtimeSources()
    /** Background notify failure must use console reporting when no reporter was configured. */
    const report = vi.spyOn(console, 'error').mockImplementation(() => undefined)
    /** The application's original failure remains distinct from configuration and wire diagnostics. */
    const failure = new RangeError('p5-default-report-fixture')
    try {
      /** Both omitted identities are generated by the same canonical Core factory owner. */
      const [client, server] = await Promise.all([
        createRuntimePeer({ connect: channel.sources[0] }),
        createRuntimePeer({
          connect: channel.sources[1],
          provide: {
            double: (value: number) => value * 2,
            fail: () => {
              throw failure
            }
          }
        })
      ])
      try {
        expect(client.self.name).toBe('peer')
        expect(client.self.instanceId).not.toBe(server.self.instanceId)
        expect(await client.request('double', 21)).toBe(42)
        await client.notify('fail')
        await expect.poll(() => report.mock.calls.length).toBeGreaterThan(0)
      } finally {
        await Promise.all([client.close(), server.close()])
      }
    } finally {
      report.mockRestore()
      channel.close()
    }
  })

  it('asyncDispose is the original close function and Promise', async () => {
    /** Typed testing Peers expose the actual Core facade, without a new cleanup owner. */
    const pairOptions = { a: { provide: {} }, b: { provide: {} } }
    /** Reuse the independently negotiated sources and actual canonical Peer constructors. */
    const pairChannel = runtimeSources(RUNTIME_API_CAPABILITIES, RUNTIME_API_CAPABILITIES)
    const [a, b] = await Promise.all([
      createRuntimePeer({
        ...pairOptions.a,
        self: { name: 'a', instanceId: 'test-pair-a' },
        connect: pairChannel.sources[0]
      }),
      createRuntimePeer({
        ...pairOptions.b,
        self: { name: 'b', instanceId: 'test-pair-b' },
        connect: pairChannel.sources[1]
      })
    ])
    const pair = { a, b }
    try {
      expect(pair.a[Symbol.asyncDispose]).toBe(pair.a.close)
      /** Concurrent explicit/scoped cleanup must retain exact original settlement identity. */
      const closing = pair.a.close()
      expect(pair.a[Symbol.asyncDispose]()).toBe(closing)
      await closing
    } finally {
      await Promise.all([pair.a.close(), pair.b.close()])
      pairChannel.close()
    }
  })

  it('raw Peer subscriptions never fabricate initial ready or native exit', async () => {
    /** Memory provides callable Peers, but has no native execution lifecycle to report. */
    const pairOptions = { a: { provide: {} }, b: { provide: {} } }
    /** Reuse the independently negotiated sources and actual canonical Peer constructors. */
    const pairChannel = runtimeSources(RUNTIME_API_CAPABILITIES, RUNTIME_API_CAPABILITIES)
    const [a, b] = await Promise.all([
      createRuntimePeer({
        ...pairOptions.a,
        self: { name: 'a', instanceId: 'test-pair-a' },
        connect: pairChannel.sources[0]
      }),
      createRuntimePeer({
        ...pairOptions.b,
        self: { name: 'b', instanceId: 'test-pair-b' },
        connect: pairChannel.sources[1]
      })
    ])
    const pair = { a, b }
    /** Factory resolution is initial readiness; a later listener must not receive a fake replay. */
    const ready = vi.fn()
    /** Closing a logical memory connection cannot counterfeit native execution exit. */
    const exit = vi.fn()
    try {
      /** The original publisher owns this exact listener receipt and idempotent cancellation. */
      const cancel = pair.a.on('ready', ready)
      pair.a.on('exit', exit)
      await Promise.resolve()
      expect(ready).not.toHaveBeenCalled()
      cancel()
      cancel()
      await pair.a.close()
      expect(exit).not.toHaveBeenCalled()
    } finally {
      await Promise.all([pair.a.close(), pair.b.close()])
      pairChannel.close()
    }
  })
})
